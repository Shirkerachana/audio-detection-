"""Step 20: Generate Log-Mel spectrograms"""

import torch
import torchaudio
import numpy as np

SAMPLE_RATE = 16000
N_FFT = 1024
HOP_LENGTH = 256
N_MELS = 64
BATCH_SIZE = 64

mel_transform = torchaudio.transforms.MelSpectrogram(
    sample_rate=SAMPLE_RATE,
    n_fft=N_FFT,
    hop_length=HOP_LENGTH,
    n_mels=N_MELS
)

def prepare_split(speech_idx, noise_idx):

    X_batches = []
    y_batches = []

    total = len(speech_idx) + len(noise_idx)

    # Process speech and noise in small batches
    for start in range(0, total, BATCH_SIZE):

        end = min(start + BATCH_SIZE, total)

        speech_count = min(
            end, len(speech_idx)
        ) - min(start, len(speech_idx))

        noise_start = max(0, start - len(speech_idx))
        noise_end = max(0, end - len(speech_idx))

        audio_batch = []

        if speech_count > 0:
            audio_batch.append(
                speech_segments[
                    speech_idx[start:start + speech_count]
                ]
            )

        if noise_end > noise_start:
            audio_batch.append(
                noise_segments[
                    noise_idx[noise_start:noise_end]
                ]
            )

        batch = np.concatenate(audio_batch, axis=0)

        waveform = torch.tensor(batch, dtype=torch.float32)

        with torch.no_grad():
            mel = mel_transform(waveform)
            log_mel = torch.log(mel + 1e-6)

        X_batches.append(log_mel)
        y_batches.append(
            torch.tensor(
                [1] * speech_count +
                [0] * (len(batch) - speech_count),
                dtype=torch.long
            )
        )

    X = torch.cat(X_batches)
    y = torch.cat(y_batches)

    # Shuffle features and labels together
    permutation = torch.randperm(len(y))

    return X[permutation], y[permutation]


