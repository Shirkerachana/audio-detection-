criterion = nn.CrossEntropyLoss(weight=class_weights)

print("Class weights:", class_weights.cpu().numpy())

for epoch in range(MAX_EPOCHS):
    epoch_start = time.time()

    # -------------------------
    # Training
    # -------------------------
    improved_model.train()

    train_loss_total = 0.0
    train_correct = 0
    train_total = 0

    for inputs, labels in tqdm(train_loader, desc=f"Epoch {epoch+1}/{MAX_EPOCHS}"):
        inputs = inputs.to(device)
        labels = labels.to(device)

        optimizer.zero_grad()

        outputs = improved_model(inputs)
        loss = criterion(outputs, labels)

        loss.backward()
        optimizer.step()

        train_loss_total += loss.item() * labels.size(0)
        predictions_batch = outputs.argmax(dim=1)

        train_correct += (predictions_batch == labels).sum().item()
        train_total += labels.size(0)

    train_loss = train_loss_total / train_total
    train_accuracy = train_correct / train_total

    # -------------------------
    # Validation
    # -------------------------
    improved_model.eval()

    val_loss_total = 0.0
    val_correct = 0
    val_total = 0

    with torch.no_grad():
        for inputs, labels in val_loader:
            inputs = inputs.to(device)
            labels = labels.to(device)

            outputs = improved_model(inputs)
            loss = criterion(outputs, labels)

            val_loss_total += loss.item() * labels.size(0)
            predictions_batch = outputs.argmax(dim=1)

            val_correct += (predictions_batch == labels).sum().item()
            val_total += labels.size(0)

    val_loss = val_loss_total / val_total
    val_accuracy = val_correct / val_total

    # -------------------------
    # Learning rate scheduler
    # -------------------------
    scheduler.step(val_loss)
    current_lr = optimizer.param_groups[0]["lr"]

    # -------------------------
    # Save history
    # -------------------------
    history["train_loss"].append(train_loss)
    history["val_loss"].append(val_loss)
    history["train_accuracy"].append(train_accuracy)
    history["val_accuracy"].append(val_accuracy)
    history["learning_rate"].append(current_lr)

    epoch_time = time.time() - epoch_start
    history["epoch_time"].append(epoch_time)

    # -------------------------
    # Checkpoint & early stopping
    # -------------------------
    if val_loss < best_val_loss:
        best_val_loss = val_loss
